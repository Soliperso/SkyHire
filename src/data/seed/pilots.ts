/** Deterministic placeholder imagery so the demo looks real without assets. */
function portfolio(seed: string, captions: string[]): PortfolioItem[] {
  return captions.map((caption, i) => ({
    id: `${seed}-p${i}`,
    imageUrl: `https://picsum.photos/seed/${seed}${i}/800/600`,
    caption,
  }))
}

